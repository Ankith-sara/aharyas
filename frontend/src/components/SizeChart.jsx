/**
 * Resolve the correct chart key from product metadata.
 * @param {string} productName
 * @param {string} category
 * @param {string} subCategory
 * @returns {keyof typeof sizeCharts}
 */
export const getSizeChartKey = (productName = '', category = '', subCategory = '') => {
    const name   = productName.toLowerCase();
    const cat    = category.toLowerCase();
    const subCat = subCategory.toLowerCase();

    // Women's products
    if (cat.includes('women') || subCat.includes('women')) {
        const isBottom = ['bottom', 'pant', 'trouser'].some(k => cat.includes(k) || subCat.includes(k));
        return isBottom ? 'womensBottoms' : 'womensTops';
    }

    // Exact product-name match
    for (const [keyword, key] of Object.entries(PRODUCT_NAME_MAP)) {
        if (name.includes(keyword)) return key;
    }

    // Category fallback
    if (cat.includes('kurta') || subCat.includes('kurta')) {
        if (name.includes('long') || subCat.includes('long'))         return 'mensLongKurta';
        if (name.includes('oversize') || subCat.includes('oversize')) return 'mensOversizeKurta';
        return 'mensShortKurta';
    }
    if (cat.includes('shirt') || subCat.includes('shirt')) {
        if (name.includes('full') || subCat.includes('full'))   return 'mensFullSleeveShirt';
        if (name.includes('tunic') || subCat.includes('tunic')) return 'mensTunicShirt';
        if (name.includes('tennis') || subCat.includes('tennis')) return 'tennisCollarShirt';
        return 'mensHalfSleeveShirt';
    }
    if (cat.includes('trouser') || subCat.includes('trouser')) return 'mensRegularTrousers';
    if (['shorts', 'half pant'].some(k => cat.includes(k) || subCat.includes(k))) {
        return name.includes('loose') || subCat.includes('loose')
            ? 'looseFitHalfPants'
            : 'regularFitHalfPants';
    }
    if (cat.includes('pant') || cat.includes('bottom')) return 'unisexRelaxedPants';

    return 'mensHalfSleeveShirt'; // safe default
};
